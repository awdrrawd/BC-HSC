import assert from 'node:assert/strict';
import { normalizeSettings, serializeSettings } from '../src/core/settings-data.js';
globalThis.window = {};
const { makeDefaultConfig } = await import('../src/core/config.js');
const defaults = makeDefaultConfig();
const changed = { ...defaults, autoWakeMin: 75, hypnoExtend: false, hypnoExtendSec: 320 };
const saved = serializeSettings(changed);
assert.deepEqual(Object.keys(saved).filter(k => k !== 'v').sort(), Object.keys(defaults).filter(k => k !== 'sounds').sort());
assert.deepEqual(normalizeSettings(defaults, JSON.parse(JSON.stringify(saved))), changed);
const legacy = normalizeSettings(defaults, { nameCensor: true, wakeWord: 'awake', arousalStep: 12, allowOthersEdit: true });
assert.equal(legacy.nameCensor, 'player');
assert.deepEqual(legacy.wakeWords, ['awake']);
assert.equal(legacy.arousalStepVoice, 12);
assert.equal(legacy.editModes.catalyst, 'any');
const invalid = normalizeSettings(defaults, { autoWakeMin: 1000, intensity: 'bad', enabled: 'false', hypnoExtendSec: -1, editModes: { catalyst: 'invalid' }, responseList: [null, 'ok'] });
assert.equal(invalid.autoWakeMin, 99);
assert.equal(invalid.intensity, defaults.intensity);
assert.equal(invalid.enabled, defaults.enabled);
assert.equal(invalid.hypnoExtendSec, 10);
assert.deepEqual(invalid.responseList, ['ok']);
for (const input of [null, [], 2, 'bad']) assert.throws(() => normalizeSettings(defaults, input));
assert.equal(serializeSettings({ ...defaults, textSource: 'DB' }).customTexts.length, 0);
console.log('Settings round trip, migration, type/range validation and persistence coverage passed.');
